// fetch-card-art.mjs — one-time asset prep. Collects every emoji used by the
// (non-bespoke) cards, resolves each to a Microsoft Fluent Emoji "3D" asset,
// downloads it locally to public/card-art/<codepoint>.webp (offline-first), and
// writes src/adventure/data/cardArtManifest.js (emoji char -> asset path).
//
//   node scripts/fetch-card-art.mjs
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CARDS } from '../src/adventure/data/cards.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'public/card-art');
fs.mkdirSync(OUT, { recursive: true });

// Name overrides where Fluent uses an older CLDR name than the dataset.
// Keyed by dataset slug -> canonical Fluent name (folder + filename derive from it).
const NAME_OVERRIDES = {
  enraged_face: 'Pouting face',                 // 😡
  smiling_face_with_open_hands: 'Hugging face', // 🤗
  t_rex: 'T-rex',                               // 🦖 (Fluent lowercases the "r")
};

const cp = (ch) => [...ch].map((c) => c.codePointAt(0).toString(16)).filter((h) => h !== 'fe0f').join('-');

// collect distinct emoji from every emoji-front card + emoji-back (illu:'emoji')
const chars = new Set();
for (const list of Object.values(CARDS)) {
  for (const c of list) {
    if (c.front && c.front.kind === 'emoji' && c.front.char) chars.add(c.front.char);
    if (c.illu === 'emoji' && c.front && c.front.char) chars.add(c.front.char);
    if (c.emoji) chars.add(c.emoji); // bespoke cards upgraded to a Fluent face
  }
}
const all = [...chars];
console.log(`distinct emoji to source: ${all.length}`);

const dataset = await (await fetch('https://cdn.jsdelivr.net/npm/unicode-emoji-json/data-by-emoji.json')).json();
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const manifest = {};
const missing = [];
let done = 0;
const limit = 10;
const queue = [...all];
async function worker() {
  while (queue.length) {
    const ch = queue.shift();
    const meta = dataset[ch] || dataset[ch + '️'];
    if (!meta) { missing.push(`${ch} (no dataset entry, cp=${cp(ch)})`); continue; }
    // Fluent: folder = capitalized CLDR name; filename = name lowercased with
    // spaces→'_' but HYPHENS KEPT (dataset slug wrongly turns hyphens into '_').
    // Skin-tone emoji live under <folder>/Default/3D/<base>_3d_default.png.
    const fluentName = NAME_OVERRIDES[meta.slug] || meta.name;
    const folder = cap(fluentName);
    const base = fluentName.toLowerCase().replace(/ /g, '_');
    const sub = meta.skin_tone_support ? `Default/3D/${base}_3d_default.png` : `3D/${base}_3d.png`;
    const url = `https://cdn.jsdelivr.net/gh/microsoft/fluentui-emoji/assets/${encodeURIComponent(folder)}/${sub.split('/').map(encodeURIComponent).join('/')}`;
    try {
      const res = await fetch(url);
      if (!res.ok) { missing.push(`${ch} → "${folder}"/${sub} (HTTP ${res.status})`); continue; }
      const buf = Buffer.from(await res.arrayBuffer());
      const name = `${cp(ch)}.webp`;
      await sharp(buf).resize(256, 256, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).webp({ quality: 90 }).toFile(path.join(OUT, name));
      manifest[ch] = `/card-art/${name}`;
      done++;
    } catch (e) { missing.push(`${ch} → ${url} (${e.message})`); }
  }
}
await Promise.all(Array.from({ length: limit }, worker));

const entries = Object.entries(manifest).sort((a, b) => a[1].localeCompare(b[1]));
const body = entries.map(([ch, p]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(p)},`).join('\n');
fs.writeFileSync(path.join(ROOT, 'src/adventure/data/cardArtManifest.js'),
  `// AUTO-GENERATED by scripts/fetch-card-art.mjs — emoji char -> Fluent 3D asset.\n// Cards whose emoji are not in this map fall back to the raster emoji glyph.\nexport const CARD_ART = {\n${body}\n};\n`);

console.log(`downloaded ${done}/${all.length} → public/card-art/, manifest written.`);
if (missing.length) { console.log(`\nMISSING (${missing.length}) — add FOLDER_OVERRIDES[slug]=folder and re-run:`); missing.forEach((m) => console.log('  ' + m)); }
